-- 13 - create bridge_award_movie tbl
CREATE TABLE bridge_movie_award (
  id_movie INTEGER NOT NULL,
  id_award INTEGER NOT NULL,
  
  -- Prevents duplicate movie-award combinations
  PRIMARY KEY (id_movie, id_award),
    
  -- Desalese Foreign Key Constraints with Cascade Delete, preventing orphaned data records.
  CONSTRAINT fk_bridge_movie_award_movie 
        FOREIGN KEY (id_movie) 
        REFERENCES movie(id_movie) 
        ON DELETE CASCADE,
        
  CONSTRAINT fk_bridge_movie_award_award
        FOREIGN KEY (id_award) 
        REFERENCES award (id_award) 
        ON DELETE CASCADE
);
-- Index on id_movie
CREATE INDEX idx_bridge_movie_award_movie
ON bridge_movie_award (id_movie);

-- Index on id_award
CREATE INDEX idx_bridge_movie_award_award
ON bridge_movie_award (id_award);

