-- 8 - create movie tbl
--DROP TABLE IF EXISTS movie CASCADE;
CREATE TABLE movie (
  id_movie INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_rating INTEGER,
  title VARCHAR(255),
  release_date DATE,
  runtime DECIMAL(5,2),
  metascore INTEGER,
  userscore DECIMAL(5,2),
  creative_type VARCHAR(255),
  url VARCHAR(255),

  CONSTRAINT fk_movie_rating					-- create id rating as FK 
  	FOREIGN KEY (id_rating) 
	REFERENCES rating (id_rating)
	
);
CREATE INDEX idx_movie_id_rating					-- Create an index called fk_movie_rating to make searches involving movie.id_rating faster. Without an index,SQL need to check many rows. lookup structure
ON movie (id_rating);

-- 9 - create sales tbl
CREATE TABLE sales (
  id_sales INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_movie INTEGER,
  production_budget DECIMAL(15,2),
  domestic_box_office DECIMAL(15,2),
  international_box_office DECIMAL(15,2),
  worldwide_box_office DECIMAL(15,2),
  opening_weekend DECIMAL(15,2),
  theatre_count INTEGER,
  avg_run_per_theatre DECIMAL(15,2),
  url VARCHAR(255),

  CONSTRAINT fk_sales_movie
        FOREIGN KEY (id_movie)
        REFERENCES movie (id_movie)

);
CREATE INDEX idx_sales_id_movie
ON sales (id_movie);

